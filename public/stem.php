<h1>Na tecnologia, há espaço para diferentes histórias.</h1>
<p>STEM reúne Ciência, Tecnologia, Engenharia e Matemática. São áreas que nos ajudam a fazer perguntas, criar ferramentas e resolver problemas — e há muitas maneiras de fazer parte delas.</p>

<h2>Mais diversidade abre mais caminhos</h2>
<p>A participação das mulheres em STEM continua desigual. A UNESCO estima que elas representam 35% das pessoas graduadas em STEM no mundo, sem mudança nessa proporção ao longo de dez anos. O número descreve um cenário global; não deve ser apresentado como um dado específico de Portugal ou do Brasil.</p>
<p>Mais informação acessível não elimina todas as barreiras. Mas pode facilitar a descoberta de formação, comunidades e oportunidades — e tornar visíveis caminhos que nem sempre são fáceis de encontrar.</p>

<h2>O papel do Women Forward</h2>
<p>O Women Forward aproxima pessoas de grupos sub-representados — com atenção especial às mulheres — de conteúdos, experiências e oportunidades em tecnologia. O conteúdo é feito por quem também percorre esses caminhos. Explore opções, conheça as entidades e escolha o próximo passo com mais informação e apoio.</p>

<h2>Aprender · Construir · Liderar</h2>
<p>Estes momentos são referências, não etapas obrigatórias. Pode começar, mudar de área, retomar os estudos ou avançar na carreira em diferentes momentos da vida.</p>

